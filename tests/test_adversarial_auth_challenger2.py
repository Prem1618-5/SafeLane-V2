@pytest.mark.unit
def test_auth_precedence_cookie_wins_over_authorization_header(client):
    """When BOTH HttpOnly Cookie (User A) and Authorization: Bearer Header (User B) are sent,
    Cookie takes precedence (User A is authenticated)."""
    jwt_cookie_user_a = create_jwt({"github_username": "cookie_alice", "github_id": 1001})
    jwt_header_user_b = create_jwt({"github_username": "header_bob", "github_id": 1002})

    client.cookies.set(SESSION_COOKIE_NAME, jwt_cookie_user_a, domain="testserver.local", path="/")

    response = client.get(
        "/api/auth/me",
        headers={"Authorization": f"Bearer {jwt_header_user_b}"},
    )
    assert response.status_code == 200
    data = response.json()
    assert data["github_username"] == "cookie_alice"
    assert data["github_id"] == 1001


