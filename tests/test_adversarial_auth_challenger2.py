@pytest.mark.unit
def test_oauth_callback_state_replay_attack(client):
    """Adversary attempts to replay a valid OAuth state that has already been consumed.
    Expected: First callback succeeds, second callback fails with HTTP 400 Bad Request."""
    # 1. Initiate login
    login_resp = client.get("/api/auth/github/login", follow_redirects=False)
    assert login_resp.status_code == 307
    state = list(_oauth_states)[0]
    assert state in _oauth_verifiers

    mock_gh_user = {"login": "attacker_or_user", "id": 112233}
    with patch("platform_app.server.routers.auth.exchange_code_for_token", new_callable=AsyncMock) as mock_exchange, \
         patch("platform_app.server.routers.auth.get_github_user", new_callable=AsyncMock) as mock_get_user, \
         patch("platform_app.server.routers.auth.upsert_user", new_callable=AsyncMock) as mock_upsert:

        mock_exchange.return_value = "gho_token_valid_1"
        mock_get_user.return_value = mock_gh_user
        mock_upsert.return_value = None

        # First callback consumes the state
        first_resp = client.get(
            f"/api/auth/github/callback?code=legit_code&state={state}",
            follow_redirects=False,
        )
        assert first_resp.status_code == 307
        assert SESSION_COOKIE_NAME in first_resp.cookies

        # Verify state and verifier were consumed and cleared
        assert state not in _oauth_states
        assert state not in _oauth_verifiers

        # Second callback with the same state must be rejected (replay protection)
        replay_resp = client.get(
            f"/api/auth/github/callback?code=legit_code&state={state}",
            follow_redirects=False,
        )
        assert replay_resp.status_code == 400
        assert replay_resp.json()["detail"] == "Invalid OAuth state parameter"


